#!/usr/bin/env node
// Builds the landing page's data files from a real sourcevision analysis of the
// n-dx monorepo — the site shows n-dx analyzing itself; nothing is invented.
//
//   assets/js/map-data.js  hero pixel map: zones, crossings, pinned findings
//   assets/js/iso-data.js  isometric map: the layout model `ndx iso` draws,
//                          produced by the checkout's own iso-map script
//
//   node scripts/build-map-data.mjs [path-to-n-dx-checkout]
//
// Defaults to ../n-dx. Run `ndx analyze --deep .` there first. Optional: the
// committed files are what the site serves, so this only needs re-running
// when you want fresher numbers.

import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { dirname, join, basename, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(process.argv[2] || join(ROOT, '..', 'n-dx'))
const SV = join(SRC, '.sourcevision')

const read = async (f) => JSON.parse(await readFile(join(SV, f), 'utf8'))

// Findings shown as callouts on the map. Matched by a prefix of the finding
// text so the copy stays sourcevision's own; `title` is the short label only.
// `at` pins a repo-wide ("global") finding to the zone it is about.
const CALLOUTS = [
  { match: 'The 109 imports from rex-prd-management', title: 'Inverted boundary' },
  { match: 'Zone-level circular dependency between scripts', title: 'Circular dependency', at: 'scripts' },
  { match: 'packages/hench/tests/helpers/index.ts imports PRDStore', title: 'Gateway bypass' },
  { match: 'The hub queue contract is duplicated by hand', title: 'Duplicated contract', at: 'web-hub' },
  { match: 'build.js copies sibling-package brand assets', title: 'Silent asset drop' },
  { match: 'Gateway erosion at the web-viewer', title: 'Gateway erosion' },
  { match: 'The golden format carries provenance', title: 'Unchecked provenance' },
  { match: 'Leaky file-format boundary with the web zone', title: 'Leaky file format' },
  { match: 'config.js is the single point', title: 'Invisible contract' },
]

const [zonesDoc, inventory, manifest] = await Promise.all([
  read('zones.json'),
  read('inventory.json'),
  read('manifest.json'),
])

const zones = zonesDoc.zones
  .map((z) => ({
    id: z.id,
    name: z.name,
    n: z.files.length,
    cohesion: z.cohesion,
    coupling: z.coupling,
    // Basenames only — enough to label a tile under the scan lens.
    files: z.files.slice(0, 90).map((f) => basename(f)),
  }))
  .sort((a, b) => b.n - a.n)

const pair = new Map()
for (const c of zonesDoc.crossings) {
  if (c.fromZone === c.toZone) continue
  const k = `${c.fromZone}>${c.toZone}`
  pair.set(k, (pair.get(k) || 0) + 1)
}
const crossings = [...pair.entries()]
  .sort((a, b) => b[1] - a[1])
  .slice(0, 18)
  .map(([k, n]) => {
    const [from, to] = k.split('>')
    return { from, to, n }
  })

const findings = CALLOUTS.map(({ match, title, at }) => {
  const f = zonesDoc.findings.find((x) => x.text.startsWith(match))
  if (!f) throw new Error(`no finding starts with: ${match}`)
  const scope = f.scope === 'global' ? at : f.scope
  const text = f.text.length > 170 ? f.text.slice(0, f.text.lastIndexOf(' ', 168)) + '…' : f.text
  return { title, severity: f.severity, type: f.type, zone: scope, text }
})

const sev = {}
for (const f of zonesDoc.findings) sev[f.severity] = (sev[f.severity] || 0) + 1

const data = {
  analyzedAt: manifest.analyzedAt,
  totals: {
    files: inventory.summary.totalFiles,
    lines: inventory.summary.totalLines,
    zones: zones.length,
    crossings: zonesDoc.crossings.filter((c) => c.fromZone !== c.toZone).length,
    findings: zonesDoc.findings.length,
    critical: sev.critical || 0,
  },
  zones,
  crossings,
  findings,
}

const out = `// Generated by scripts/build-map-data.mjs from a sourcevision analysis of the
// n-dx monorepo (${data.analyzedAt.slice(0, 10)}). Do not hand-edit.
window.NDX_MAP = ${JSON.stringify(data)};
`
await writeFile(join(ROOT, 'assets', 'js', 'map-data.js'), out, 'utf8')
console.log(`map-data.js: ${data.totals.files} files, ${zones.length} zones, ${findings.length} callouts`)

// ── iso model ────────────────────────────────────────────────────────────
// Run the checkout's portable iso-map script rather than re-deriving layout
// here: block sizes, colours, layering and edge routes then match `ndx iso`
// exactly. Its HTML goes to a temp dir; only the --json model is kept.
const tmp = await mkdtemp(join(tmpdir(), 'ndx-iso-'))
let model
try {
  const json = execFileSync(
    process.execPath,
    [join(SRC, '.claude/skills/iso-map/scripts/iso-map.mjs'), SRC, '--source=sourcevision', '--no-externals', `--out=${join(tmp, 'iso.html')}`, '--json'],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] }
  )
  model = JSON.parse(json)
} finally {
  await rm(tmp, { recursive: true, force: true })
}

// Trim to what the page draws. Source links are dropped: they point at the
// repository the analysis ran in, which is not necessarily public.
const iso = {
  meta: {
    project: model.meta.project,
    analyzedAt: model.meta.analyzedAt,
    zones: model.meta.totalZones,
    files: model.meta.totalFiles,
    lines: model.meta.totalLines,
  },
  kinds: model.kinds.map(({ id, label, color, glyph }) => ({ id, label, color, glyph })),
  bounds: model.bounds,
  nodes: model.nodes.map((n) => ({
    id: n.id,
    kind: n.kind,
    stage: n.stage,
    u: n.u, v: n.v, w: n.w, d: n.d, h: n.h,
    files: n.metrics.files,
    lines: n.metrics.lines,
    cohesion: n.metrics.cohesion,
    coupling: n.metrics.coupling,
    findings: (n.findings || []).filter((f) => f.severity !== 'info').slice(0, 3).map((f) => ({ text: f.text, severity: f.severity })),
  })),
  edges: model.edges.map((e) => ({ from: e.from, to: e.to, weight: e.weight, back: !!e.back, points: e.points })),
}
await writeFile(
  join(ROOT, 'assets', 'js', 'iso-data.js'),
  `// Generated by scripts/build-map-data.mjs from the iso-map model of the n-dx\n// monorepo (${iso.meta.analyzedAt.slice(0, 10)}). Do not hand-edit.\nwindow.NDX_ISO = ${JSON.stringify(iso)};\n`,
  'utf8'
)
console.log(`iso-data.js: ${iso.nodes.length} blocks, ${iso.edges.length} edges`)
